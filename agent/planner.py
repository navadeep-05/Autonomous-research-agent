from groq import Groq
from dotenv import load_dotenv
import os

# Load the variables from the .env file
load_dotenv()

# Create the Groq client using our API key
client = Groq(
    api_key=os.getenv("GROQ_API_KEY")
)

# Model used for our project
MODEL = "openai/gpt-oss-20b"


def create_research_plan(question):
    """
    Break the user's research question into smaller research tasks.
    Returns a list of task strings. Never raises.
    """

    try:
        # Ask the LLM to create a research plan
        response = client.chat.completions.create(
            model=MODEL,
            messages=[
                {
                    "role": "system",
                    "content": """
You are a research planning agent.

Your job is to break the user's research question
into exactly 3 clear and independent research subtasks.
Planning is a separate phase, not one of the research subtasks.

Each task should focus on one specific aspect of
the question.

Return ONLY a numbered list.
Do not provide explanations or answers.
"""
                },
                {
                    "role": "user",
                    "content": question
                }
            ],

            # Keep the response reasonably small
            max_completion_tokens=300
        )

        # Get the text generated by the model
        raw_plan = response.choices[0].message.content
        if not raw_plan:
            return [question]

        # Convert the numbered text into a Python list
        plan = []

        for line in raw_plan.splitlines():

            # Remove unnecessary spaces
            line = line.strip()

            # Ignore empty lines
            if not line:
                continue

            # Remove numbering such as "1.", "2.", etc.
            task = line.lstrip("0123456789.-) ").strip()

            # Add the cleaned task to our plan
            if task:
                plan.append(task)

        # Return the final research plan
        return plan[:3] if plan else [question]

    except Exception as e:
        print(f"[planner] Error: {e}")
        return [question]


# Test the planner when this file is run directly
if __name__ == "__main__":

    # Ask the user for a research question
    question = input("Enter your research question: ")

    # Generate the research plan
    plan = create_research_plan(question)

    # Display the generated plan
    print("\n========== RESEARCH PLAN ==========\n")

    for index, task in enumerate(plan, start=1):
        print(f"{index}. {task}")